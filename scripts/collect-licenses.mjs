#!/usr/bin/env node
// Writes src/assets/licenses/NPM-PACKAGES.txt: every npm package the panels
// ship (the production dependency tree, not dev tools), each with its name,
// version, declared license and the full text of its own LICENSE/NOTICE
// files. MIT, Apache-2.0 and similar licenses require that text to travel
// with the software; the licenses folder is copied into every package by
// cep.config.ts. release.mjs runs this before building.
//
// Usage (from the project root):  node scripts/collect-licenses.mjs
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(ROOT, "src", "assets", "licenses", "NPM-PACKAGES.txt");

// `npm ls` exits non-zero on any tree problem (an extraneous package, an
// unmet optional one) while still printing the full JSON, so read its output
// either way and only fail if there is none. The project's own optional
// dependencies are left out as well (npm ls applies --omit only at the top
// level): jsxbin, the only one, is a build tool used only by the jsxbin build
// and never ships.
const ls = spawnSync("npm", ["ls", "--omit=dev", "--omit=optional", "--all", "--json", "--long"], {
  cwd: ROOT,
  maxBuffer: 64 << 20,
  encoding: "utf8",
});
if (!ls.stdout) throw new Error(`npm ls produced no output: ${ls.stderr}`);
if (ls.status !== 0) console.warn("npm ls reported dependency-tree problems (listed by `npm ls`); continuing with the tree it printed.");
const tree = JSON.parse(ls.stdout);

const seen = new Map();
const walk = (deps) => {
  for (const [name, info] of Object.entries(deps || {})) {
    if (!info || !info.path || info.extraneous) continue;
    const key = `${name}@${info.version}`;
    if (!seen.has(key)) seen.set(key, { name, version: info.version, dir: info.path });
    walk(info.dependencies);
  }
};
walk(tree.dependencies);

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$|^licen[cs]e[-_.]/i;
const sections = [];
for (const pkg of [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const meta = JSON.parse(fs.readFileSync(path.join(pkg.dir, "package.json"), "utf8"));
  const license = typeof meta.license === "string" ? meta.license : meta.license?.type || "(not declared)";
  const repo = typeof meta.repository === "string" ? meta.repository : meta.repository?.url || meta.homepage || "";
  const texts = fs
    .readdirSync(pkg.dir)
    .filter((f) => LICENSE_FILE.test(f) && fs.statSync(path.join(pkg.dir, f)).isFile())
    .sort()
    .map((f) => `--- ${f} ---\n${fs.readFileSync(path.join(pkg.dir, f), "utf8").trim()}`);
  sections.push(
    [
      `${pkg.name}@${pkg.version}`,
      `License: ${license}`,
      repo ? `Source: ${repo}` : "",
      texts.length ? texts.join("\n\n") : "(no license file in the package; see its declared license above)",
    ]
      .filter(Boolean)
      .join("\n"),
  );
}

const header =
  "npm packages in AI Voice Master Tool's production dependency tree, with their licenses.\n" +
  "This is a superset of what the panels' bundles contain (for example, native image modules\n" +
  "that only Node builds of a dependency use are listed but not shipped).\n" +
  "Generated by scripts/collect-licenses.mjs.\n" +
  `${seen.size} packages.\n`;
fs.writeFileSync(out, header + "\n" + sections.join("\n\n" + "=".repeat(78) + "\n\n") + "\n");
console.log(`wrote ${path.relative(ROOT, out)} (${seen.size} packages)`);
